func assertRealContextBoundaries(t *testing.T, collector *Collector, source SourceConfig) {
	t.Helper()
	cancelled, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := collector.Inspect(cancelled, source); sourceErrorCode(err) != "cancelled" {
		t.Fatalf("real driver cancellation was not classified: %v", err)
	}
	timedOut, cancel := context.WithTimeout(context.Background(), time.Nanosecond)
	defer cancel()
	if _, err := collector.Inspect(timedOut, source); sourceErrorCode(err) != "timeout" {
		t.Fatalf("real driver timeout was not classified: %v", err)
	}
}

