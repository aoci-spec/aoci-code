// prepareLocaleChange changes only configuration state. Existing formal
// assets are inventoried into a resumable receipt and remain untouched until
// the regular Header, Entries, and Curation governance pipelines apply their
// reviewed replacements.
func prepareLocaleChange(root string, cfg *config.Config, target string) error {
	if cfg == nil {
		return errors.New(cliMessage("locale.config_unavailable"))
	}
	if cfg.LocaleMigration != nil {
		if cfg.LocaleMigration.ToLocale == target && cfg.Locale == target {
			return nil
		}
		return errors.New(cliMessage(
			"locale.migration_in_progress",
			cfg.LocaleMigration.FromLocale,
			cfg.LocaleMigration.ToLocale,
		))
	}
	if err := requireLegacyWriteLayout(root, cfg, true); err != nil {
		return err
	}

	indexPath := filepath.Join(root, filepath.FromSlash(cfg.IndexPath))
	data, err := os.ReadFile(indexPath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			cfg.Locale = target
			return nil
		}
		return errors.New(cliMessage("locale.read_index_error", err))
	}

	fromLocale, _, err := index.DetectLocale(string(data))
	if err != nil {
		return errors.New(cliMessage("locale.detect_index_error", err))
	}
	if fromLocale == target {
		cfg.Locale = target
		cfg.LocaleMigration = nil
		return nil
	}
	// The Legacy authoring surfaces that re-authored a Header and its Entries
	// in the new Locale are retired (0.2.0): a Legacy index keeps the Locale
	// it was written in until it migrates to Volumes.
	return errors.New(cliMessage("locale.legacy_read_only", fromLocale, target))
}

// Coverage of a pending Legacy locale migration, reported by check for
// repositories that still carry such a receipt from an earlier release.
type localeMigrationCoverageCount struct {
	Total   int `json:"total"`
	Pending int `json:"pending"`
}

type localeMigrationCoverageStatus struct {
	Total   int    `json:"total"`
	Pending int    `json:"pending"`
	Status  string `json:"status"`
}

type localeMigrationExclusion struct {
	Surface string `json:"surface"`
	Reason  string `json:"reason"`
}

type localeMigrationUnresolved struct {
	Target string `json:"target"`
	Count  int    `json:"count"`
	Reason string `json:"reason"`
}

type localeMigrationCoverage struct {
	Active             bool                          `json:"active"`
	FromLocale         string                        `json:"from_locale,omitempty"`
	ToLocale           string                        `json:"to_locale,omitempty"`
	Header             localeMigrationCoverageCount  `json:"header"`
	OrdinaryEntries    localeMigrationCoverageCount  `json:"ordinary_entries"`
	GovernanceEntries  localeMigrationCoverageCount  `json:"governance_entries"`
	Curation           localeMigrationCoverageCount  `json:"curation"`
	ManagedIndexText   localeMigrationCoverageCount  `json:"managed_index_text"`
	AgentsManagedBlock localeMigrationCoverageStatus `json:"agents_managed_block"`
	RuntimeContracts   localeMigrationCoverageStatus `json:"runtime_contracts"`
	Excluded           []localeMigrationExclusion    `json:"excluded"`
	Unresolved         []localeMigrationUnresolved   `json:"unresolved"`
}

// isAOCIGovernanceEntryPath identifies repository-internal machine governance
// assets. They are not source-semantic Entry targets: their append-only or
// machine-generated bytes must never be used as locale-migration evidence.
func isAOCIGovernanceEntryPath(relPath string) bool {
	relPath = strings.TrimPrefix(filepath.ToSlash(strings.TrimSpace(relPath)), "./")
	return relPath == config.DirName || strings.HasPrefix(relPath, config.DirName+"/")
}

// ensureManagedAgentsLocale rewrites only the AOCI-managed AGENTS block from
// the target catalog. Locale migration cannot clear its Header prerequisite
// until this deterministic project contract is also in the target language.
func ensureManagedAgentsLocale(root, locale string) error {
	previous := textassets.ActiveLocale()
	if err := textassets.SetActiveLocale(locale); err != nil {
		return err
	}
	_, updateErr := hooks.EnsureAgentsBlock(root)
	restoreErr := textassets.SetActiveLocale(previous)
	if updateErr != nil {
		return updateErr
	}
	return restoreErr
}

func sortedLocaleMigrationPaths(paths map[string]struct{}) []string {
	result := make([]string, 0, len(paths))
	for path := range paths {
		result = append(result, path)
	}
	sort.Strings(result)
	return result
}

func splitLocaleMigrationEntryPaths(migration *config.LocaleMigration) (ordinary, governance []string) {
	if migration == nil {
		return nil, nil
	}
	governanceSet := map[string]struct{}{}
	for _, relPath := range migration.GovernanceEntryPaths {
		governanceSet[relPath] = struct{}{}
	}
	for _, relPath := range migration.EntryPaths {
		if isAOCIGovernanceEntryPath(relPath) {
			governanceSet[relPath] = struct{}{}
			continue
		}
		ordinary = append(ordinary, relPath)
	}
	governance = sortedLocaleMigrationPaths(governanceSet)
	return ordinary, governance
}

func buildLocaleMigrationCoverage(cfg *config.Config) localeMigrationCoverage {
	coverage := localeMigrationCoverage{
		Excluded: []localeMigrationExclusion{
			{Surface: "paths_identifiers_apis_and_project_names", Reason: cliMessage("locale.coverage.exclude_identity")},
			{Surface: "source_and_source_comments", Reason: cliMessage("locale.coverage.exclude_source")},
			{Surface: "agents_unmanaged_region_and_user_documents", Reason: cliMessage("locale.coverage.exclude_user")},
		},
		Unresolved: []localeMigrationUnresolved{},
	}
	if cfg == nil || cfg.LocaleMigration == nil {
		coverage.AgentsManagedBlock.Status = "aligned"
		coverage.RuntimeContracts.Status = "aligned"
		return coverage
	}
	migration := cfg.LocaleMigration
	ordinary, governance := splitLocaleMigrationEntryPaths(migration)
	ordinaryTotal := migration.EntryTotal
	legacyGovernance := len(migration.EntryPaths) - len(ordinary)
	if legacyGovernance > 0 && migration.GovernanceEntryTotal == 0 {
		ordinaryTotal -= legacyGovernance
	}
	governanceTotal := migration.GovernanceEntryTotal
	if governanceTotal < len(governance) {
		governanceTotal = len(governance)
	}
	coverage.Active = true
	coverage.FromLocale = migration.FromLocale
	coverage.ToLocale = migration.ToLocale
	coverage.Header = localeMigrationCoverageCount{Total: migration.HeaderTotal, Pending: boolCount(migration.HeaderPending)}
	coverage.OrdinaryEntries = localeMigrationCoverageCount{Total: ordinaryTotal, Pending: len(ordinary)}
	coverage.GovernanceEntries = localeMigrationCoverageCount{Total: governanceTotal, Pending: len(governance)}
	coverage.Curation = localeMigrationCoverageCount{Total: migration.CurationTotal, Pending: len(migration.CurationPaths)}
	coverage.ManagedIndexText = localeMigrationCoverageCount{Total: migration.ManagedIndexTextTotal, Pending: pendingTotal(migration.ManagedIndexTextPending, migration.ManagedIndexTextTotal)}
	coverage.AgentsManagedBlock = localeMigrationCoverageStatus{Total: migration.AgentsManagedBlockTotal, Pending: boolCount(migration.AgentsManagedBlockPending), Status: pendingStatus(migration.AgentsManagedBlockPending)}
	coverage.RuntimeContracts = localeMigrationCoverageStatus{Total: 1, Pending: 0, Status: "target_locale_catalog_active"}
	appendUnresolved := func(target string, count int, reason string) {
		if count > 0 {
			coverage.Unresolved = append(coverage.Unresolved, localeMigrationUnresolved{Target: target, Count: count, Reason: reason})
		}
	}
	appendUnresolved("header", coverage.Header.Pending, cliMessage("locale.coverage.pending_header"))
	appendUnresolved("ordinary_entries", coverage.OrdinaryEntries.Pending, cliMessage("locale.coverage.pending_entries"))
	appendUnresolved("governance_entries", coverage.GovernanceEntries.Pending, cliMessage("locale.coverage.pending_governance"))
	appendUnresolved("curation", coverage.Curation.Pending, cliMessage("locale.coverage.pending_curation"))
	appendUnresolved("managed_index_text", coverage.ManagedIndexText.Pending, cliMessage("locale.coverage.pending_index_text"))
	appendUnresolved("agents_managed_block", coverage.AgentsManagedBlock.Pending, cliMessage("locale.coverage.pending_agents"))
	return coverage
}

func boolCount(value bool) int {
	if value {
		return 1
	}
	return 0
}

func pendingTotal(pending bool, total int) int {
	if pending {
		return total
	}
	return 0
}

func pendingStatus(pending bool) string {
	if pending {
		return "pending"
	}
	return "aligned"
}
