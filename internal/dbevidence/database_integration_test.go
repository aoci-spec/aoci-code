func blackholeDSN(t *testing.T, engine Engine, original string) string {
	t.Helper()
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	done := make(chan struct{})
	go func() {
		for {
			connection, err := listener.Accept()
			if err != nil {
				return
			}
			go func() {
				defer connection.Close()
				<-done
			}()
		}
	}()
	t.Cleanup(func() {
		close(done)
		_ = listener.Close()
	})
	return replaceDSNAddress(t, engine, original, listener.Addr().String())
}

