func assertRepeatedSnapshotBytes(t *testing.T, first Snapshot, firstFiles map[string][]byte, second Snapshot, secondFiles map[string][]byte) {
	t.Helper()
	firstBytes, err := CanonicalJSON(first)
	if err != nil {
		t.Fatal(err)
	}
	secondBytes, err := CanonicalJSON(second)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(firstBytes, secondBytes) || !reflect.DeepEqual(firstFiles, secondFiles) {
		t.Fatal("repeated live catalog collection did not produce byte-identical canonical Evidence")
	}
}

func acceptRealSnapshot(t *testing.T, root string, manifest SourceManifest, snapshot Snapshot, files map[string][]byte) (Baseline, []byte) {
	t.Helper()
	if err := WriteSnapshot(root, manifest, snapshot, files); err != nil {
		t.Fatal(err)
	}
	if err := AcceptSnapshot(root, snapshot, snapshot.SourceSnapshotSHA256); err != nil {
		t.Fatal(err)
	}
	baseline, exists, err := LoadBaseline(root)
	if err != nil || !exists {
		t.Fatalf("real Evidence Baseline was not persisted: exists=%t err=%v", exists, err)
	}
	data, err := os.ReadFile(BaselinePath(root))
	if err != nil {
		t.Fatal(err)
	}
	return baseline, data
}

func assertBaselineUnchanged(t *testing.T, root string, accepted []byte) {
	t.Helper()
	current, err := os.ReadFile(BaselinePath(root))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(current, accepted) {
		t.Fatal("live drift verification advanced the Database Evidence Baseline")
	}
}

func assertUnrelatedTableStable(t *testing.T, before, after Snapshot, objectRef string) {
	t.Helper()
	beforeTable := snapshotRecord(t, before, objectRef)
	afterTable := snapshotRecord(t, after, objectRef)
	if beforeTable.TableEvidenceSHA256 != afterTable.TableEvidenceSHA256 {
		t.Fatalf("unrelated table fingerprint changed for %s", objectRef)
	}
}

func snapshotRecord(t *testing.T, snapshot Snapshot, objectRef string) SnapshotTable {
	t.Helper()
	for _, table := range snapshot.Tables {
		if table.ObjectRef == objectRef {
			return table
		}
	}
	t.Fatalf("snapshot omitted %s", objectRef)
	return SnapshotTable{}
}

func assertSystemNamespacesExcluded(t *testing.T, snapshot Snapshot, forbidden ...string) {
	t.Helper()
	for _, table := range snapshot.Tables {
		for _, namespace := range forbidden {
			if table.ObjectRef == "database://"+snapshot.SourceID+"/"+namespace || strings.Contains(table.ObjectRef, "/"+namespace+"/") {
				t.Fatalf("system namespace entered Evidence: %s", table.ObjectRef)
			}
		}
	}
}

func assertSavedEvidenceSurvivesFailure(t *testing.T, root string, collector *Collector, source SourceConfig, snapshotSHA string) {
	t.Helper()
	bad := source
	bad.CredentialEnv = "AOCI_TEST_DATABASE_FAILURE_DSN"
	t.Setenv(bad.CredentialEnv, unreachableDSN(t, source.Engine, os.Getenv(source.CredentialEnv)))
	if _, _, _, err := collector.Snapshot(context.Background(), bad); err == nil {
		t.Fatal("unavailable source unexpectedly produced Evidence")
	}
	_, stored, exists, err := LoadSnapshot(root, source.SourceID)
	if err != nil || !exists || stored.SourceSnapshotSHA256 != snapshotSHA {
		t.Fatalf("source failure damaged the previous saved Evidence: exists=%t err=%v", exists, err)
	}
}

func logRealAcceptance(t *testing.T, engine string, snapshot Snapshot, baseline Baseline, drift DriftReport, objectRef string, files map[string][]byte) {
	t.Helper()
	assertRealAcceptanceGolden(t, engine, snapshot, drift, objectRef, files)
	record := snapshotRecord(t, snapshot, objectRef)
	var acceptedSHA string
	for _, source := range baseline.Sources {
		if source.SourceID == snapshot.SourceID {
			acceptedSHA = source.SourceSnapshotSHA256
		}
	}
	if acceptedSHA != snapshot.SourceSnapshotSHA256 {
		t.Fatal("persisted Baseline is not bound to the accepted real snapshot")
	}
	table := TableEvidence{}
	if err := decodeStrict(files[objectRef], &table); err != nil {
		t.Fatal(err)
	}
	bundle := BuildEvidenceBundle(table, record.TableEvidenceSHA256, []string{"fixture://migration"}, []string{"fixture://code"}, nil)
	bundleBytes, err := CanonicalJSON(bundle)
	if err != nil || bundle.SemanticCandidateIncluded || bundle.BusinessDataRead {
		t.Fatalf("unsafe Evidence Bundle: err=%v", err)
	}
	if strings.Contains(string(bundleBytes), "F:") || strings.Contains(string(bundleBytes), "R:") || strings.Contains(string(bundleBytes), businessSentinel) {
		t.Fatal("Evidence Bundle contained generated FRAS or business row data")
	}
	t.Logf("database_acceptance engine=%s object_ref=%s table_evidence_sha256=%s source_snapshot_sha256=%s baseline_source_snapshot_sha256=%s tables=%d drift_unchanged=%d drift_new=%d drift_changed=%d drift_removed=%d business_data_read=false", engine, objectRef, record.TableEvidenceSHA256, snapshot.SourceSnapshotSHA256, acceptedSHA, len(snapshot.Tables), drift.Summary.Unchanged, drift.Summary.New, drift.Summary.Changed, drift.Summary.Removed)
	t.Logf("canonical_table_evidence engine=%s base64=%s", engine, base64.StdEncoding.EncodeToString(files[objectRef]))
}

func assertRealAcceptanceGolden(t *testing.T, engine string, snapshot Snapshot, drift DriftReport, objectRef string, files map[string][]byte) {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", "real", "acceptance.json"))
	if err != nil {
		t.Fatal(err)
	}
	var golden realAcceptanceGolden
	if err := decodeStrict(data, &golden); err != nil || golden.Version != "database-real-acceptance/v1" {
		t.Fatalf("invalid real acceptance Golden: %v", err)
	}
	for _, candidate := range golden.Engines {
		if candidate.Engine != engine {
			continue
		}
		record := snapshotRecord(t, snapshot, objectRef)
		if candidate.ObjectRef != objectRef || candidate.TableEvidenceSHA256 != record.TableEvidenceSHA256 || candidate.SourceSnapshotSHA256 != snapshot.SourceSnapshotSHA256 || candidate.TableCount != len(snapshot.Tables) || candidate.Drift != drift.Summary {
			t.Fatalf("real %s acceptance identity drifted: snapshot=%s table=%s count=%d drift=%+v", engine, snapshot.SourceSnapshotSHA256, record.TableEvidenceSHA256, len(snapshot.Tables), drift.Summary)
		}
		expected, err := os.ReadFile(candidate.CanonicalEvidenceRef)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(expected, files[objectRef]) {
			t.Fatalf("real %s Canonical Table Evidence drifted from its reviewed Golden", engine)
		}
		return
	}
	t.Fatalf("real acceptance Golden omitted engine %s", engine)
}

func assertPostgreSQLVisibilityBoundary(t *testing.T, adminDSN, credential string, collector *Collector, source SourceConfig) {
	t.Helper()
	partial := source
	partial.CredentialEnv = "AOCI_TEST_DATABASE_PARTIAL_DSN"
	t.Setenv(partial.CredentialEnv, postgresqlUserDSN(t, adminDSN, "aoci_d0_partial", credential))
	_, snapshot, _, err := collector.Snapshot(context.Background(), partial)
	if err != nil {
		t.Fatal(err)
	}
	if len(snapshot.Tables) != 4 {
		t.Fatalf("PostgreSQL partial reader saw %d tables, want 4", len(snapshot.Tables))
	}
	for _, table := range snapshot.Tables {
		if !strings.Contains(table.ObjectRef, "/aoci_d0/") {
			t.Fatalf("PostgreSQL partial reader crossed its granted schema: %s", table.ObjectRef)
		}
	}

	admin, err := sql.Open("pgx", adminDSN)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()
	if _, err := admin.ExecContext(context.Background(), `REVOKE SELECT ON pg_catalog.pg_partitioned_table FROM PUBLIC`); err != nil {
		t.Fatal("temporary PostgreSQL metadata permission setup failed")
	}
	restored := false
	defer func() {
		if !restored {
			_, _ = admin.ExecContext(context.Background(), `GRANT SELECT ON pg_catalog.pg_partitioned_table TO PUBLIC`)
		}
	}()
	if _, _, _, err := collector.Snapshot(context.Background(), source); sourceErrorCode(err) != "permission_denied" {
		t.Fatalf("PostgreSQL metadata denial classification failed: %s", sourceErrorCode(err))
	}
	if _, err := admin.ExecContext(context.Background(), `GRANT SELECT ON pg_catalog.pg_partitioned_table TO PUBLIC`); err != nil {
		t.Fatal("temporary PostgreSQL metadata permission restoration failed")
	}
	restored = true
}

